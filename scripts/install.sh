#!/usr/bin/env bash
# Install the development build for the current user. It creates the app copy,
# launchers and a marked zsh auto-start block; it never edits Kiro config.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SOURCE="${1:-$ROOT/dist/Offline Complete.app}"
DEST="$HOME/Applications/Offline Complete.app"
LAUNCHER="$HOME/.local/bin/oc"

if [ ! -d "$SOURCE" ]; then
  echo "install: build first with 'make dist' (missing $SOURCE)" >&2
  exit 1
fi

mkdir -p "$HOME/Applications" "$HOME/.local/bin"
rm -rf "$DEST"
cp -R "$SOURCE" "$DEST"

cat > "$LAUNCHER" <<'LAUNCHER_EOF'
#!/bin/sh
# offline-complete launcher (generated by scripts/install.sh)
APP="$HOME/Applications/Offline Complete.app"
if [ ! -x "$APP/Contents/MacOS/offline-complete" ]; then
  export OFFLINE_COMPLETE_ACTIVE=1
  exec /bin/zsh -i
fi
if [ "$#" -eq 0 ]; then
  set -- zsh -i
fi
export OFFLINE_COMPLETE_RULES="$APP/Contents/Resources/rules.bin"
exec "$APP/Contents/MacOS/offline-complete" "$@"
LAUNCHER_EOF
chmod 0755 "$LAUNCHER"

for tool in oc-manage oc-window oc-client oc-app; do
  cat > "$HOME/.local/bin/$tool" <<EOF
#!/bin/sh
# offline-complete launcher (generated by scripts/install.sh)
exec "\$HOME/Applications/Offline Complete.app/Contents/MacOS/$tool" "\$@"
EOF
  chmod 0755 "$HOME/.local/bin/$tool"
done

# Enable automatic startup for new interactive zsh windows. The block is
# marked and can be removed with oc-manage shell uninstall.
if ! "$HOME/.local/bin/oc-manage" shell install --oc "$HOME/.local/bin/oc"; then
  echo "warning: zsh integration failed; run: $HOME/.local/bin/oc-manage shell install" >&2
fi

echo "installed: $DEST"
echo "launcher:  $LAUNCHER"
echo "shell:     open the app; auto-start is active while the app is running"
echo
echo "Main window: open \"$DEST\""
echo "Add ~/.local/bin to PATH to use 'oc' directly."
echo "Remove shell integration with: oc-manage shell uninstall"
