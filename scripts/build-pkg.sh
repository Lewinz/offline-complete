#!/usr/bin/env bash
# Build a local component installer for /Applications and /usr/local/bin.
# The package is unsigned unless a Developer ID Installer identity is supplied
# later; this script only prepares the development package.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
APP="$ROOT/dist/Offline Complete.app"
OUT="$ROOT/dist/Offline-Complete.pkg"
PKG_ID="dev.offlinecomplete.pkg"
APP_PATH="/Applications/Offline Complete.app"

if [ ! -d "$APP" ]; then
  echo "pkg: build the app first with 'make dist' (missing $APP)" >&2
  exit 1
fi

VERSION="$(/usr/libexec/PlistBuddy -c 'Print :CFBundleShortVersionString' "$APP/Contents/Info.plist")"
STAGE="$(mktemp -d "${TMPDIR:-/tmp}/offline-complete-pkg.XXXXXX")"
SCRIPTS="$(mktemp -d "${TMPDIR:-/tmp}/offline-complete-scripts.XXXXXX")"
trap 'rm -rf "$STAGE" "$SCRIPTS"' EXIT

mkdir -p "$STAGE/Applications" "$STAGE/usr/local/bin"
/usr/bin/ditto "$APP" "$STAGE/Applications/Offline Complete.app"

cat > "$STAGE/usr/local/bin/oc" <<'LAUNCHER'
#!/bin/sh
# offline-complete launcher (generated by build-pkg.sh)
APP="/Applications/Offline Complete.app"
if [ ! -x "$APP/Contents/MacOS/offline-complete" ]; then
  export OFFLINE_COMPLETE_ACTIVE=1
  exec /bin/zsh -i
fi
if [ "$#" -eq 0 ]; then
  set -- zsh -i
fi
export OFFLINE_COMPLETE_RULES="$APP/Contents/Resources/rules.bin"
exec "$APP/Contents/MacOS/offline-complete" "$@"
LAUNCHER

write_tool() {
  name="$1"
  cat > "$STAGE/usr/local/bin/$name" <<EOF
#!/bin/sh
# offline-complete launcher (generated by build-pkg.sh)
exec "$APP_PATH/Contents/MacOS/$name" "\$@"
EOF
}

for tool in oc-app oc-manage oc-window oc-client; do
  write_tool "$tool"
done
chmod 0755 "$STAGE/usr/local/bin/"*

cat > "$SCRIPTS/preinstall" <<'PREINSTALL'
#!/bin/sh
set -eu
for name in oc oc-app oc-manage oc-window oc-client; do
  path="/usr/local/bin/$name"
  if [ -e "$path" ] && ! grep -q 'offline-complete launcher' "$path" 2>/dev/null; then
    echo "installer: $path already exists and does not belong to Offline Complete" >&2
    echo "installer: move or remove that command, then run the installer again" >&2
    exit 1
  fi
done
exit 0
PREINSTALL
chmod 0755 "$SCRIPTS/preinstall"

cat > "$SCRIPTS/postinstall" <<'POSTINSTALL'
#!/bin/sh
set -eu
console_user="$(/usr/bin/stat -f %Su /dev/console 2>/dev/null || true)"
if [ -z "$console_user" ] || [ "$console_user" = "root" ] || [ "$console_user" = "_mbsetupuser" ]; then
  echo "installer: no console zsh user; run 'oc-manage shell install' as the target user" >&2
  exit 0
fi
console_home="$(/usr/bin/dscl . -read "/Users/$console_user" NFSHomeDirectory 2>/dev/null | /usr/bin/awk '{print $2}')"
if [ -z "$console_home" ] || [ ! -x /usr/local/bin/oc-manage ]; then
  echo "installer: could not install zsh integration automatically" >&2
  exit 0
fi
/usr/bin/su -l "$console_user" -c "/usr/local/bin/oc-manage shell install --home \"$console_home\" --oc /usr/local/bin/oc" || {
  echo "installer: zsh integration failed; run 'oc-manage shell install' as the user" >&2
}
exit 0
POSTINSTALL
chmod 0755 "$SCRIPTS/postinstall"

# Avoid AppleDouble metadata entries in the installer payload.
/usr/bin/xattr -cr "$STAGE" 2>/dev/null || true

rm -f "$OUT"
COPYFILE_DISABLE=1 /usr/bin/pkgbuild \
  --root "$STAGE" \
  --identifier "$PKG_ID" \
  --version "$VERSION" \
  --install-location / \
  --scripts "$SCRIPTS" \
  "$OUT"

echo "package: $OUT"
echo "installs: $APP_PATH"
echo "commands: /usr/local/bin/{oc,oc-app,oc-manage,oc-window,oc-client}"
echo "uninstall: sudo scripts/uninstall-pkg.sh"
